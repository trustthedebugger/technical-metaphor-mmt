"""Paper tables from every run in ../results/*/runs. Rerun after new results arrive.
Usage: python make_tables.py > tables.md"""
import glob, json, os
from math import comb
import numpy as np
from scipy.stats import mannwhitneyu

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "results")
runs = {}
for d in glob.glob(f"{ROOT}/*/runs/*/results.json"):
    d = os.path.dirname(d)
    cfg = json.load(open(f"{d}/config.json"))
    runs.setdefault(cfg["system"], {})[cfg["seed"]] = d


def sign_p(r, w):
    n = r + w
    return min(1.0, 2 * sum(comb(n, i) for i in range(min(r, w) + 1)) / 2 ** n) if n else 1.0


def one(d):
    res = json.load(open(f"{d}/results.json"))
    m = np.loadtxt(f"{d}/commute_incorrect.txt") - np.loadtxt(f"{d}/commute_correct.txt")
    x, y = m[0::2], m[1::2]
    out = dict(val=res["best_val_bleu"], bleu=res["test2016_correct"]["bleu"], chrf=res["test2016_correct"]["chrf"],
               com=res["commute_accuracy"], right=int(((x > 0) & (y > 0)).sum()), wrong=int(((x < 0) & (y < 0)).sum()),
               soft=res.get("soft_test", {}).get("bleu"), auc=None, shuf=None)
    if "test2016_shuffled" in res:
        out["shuf"] = res["test2016_correct"]["bleu"] - res["test2016_shuffled"]["bleu"]
    if os.path.exists(f"{d}/gate_values.txt"):
        g, l = np.loadtxt(f"{d}/gate_values.txt"), np.loadtxt(f"{d}/gate_labels.txt")
        out["auc"] = mannwhitneyu(g[l == 1], g[l == 0]).statistic / ((l == 1).sum() * (l == 0).sum())
    return out


def ms(vals, f="{:.2f}"):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "–"
    return f.format(vals[0]) if len(vals) == 1 else f"{f.format(np.mean(vals))} ± {f.replace('+', '').format(np.std(vals, ddof=1))}"


def row(system, label=None, seeds=None):
    if system not in runs:
        return f"| {label or system} | pending |" + " |" * 8
    ss = sorted(s for s in runs[system] if seeds is None or s in seeds)
    rs = [one(runs[system][s]) for s in ss]
    r, w = sum(x["right"] for x in rs), sum(x["wrong"] for x in rs)
    p = sign_p(r, w)
    return (f"| {label or system} | {','.join(map(str, ss))} | {ms([x['val'] for x in rs])} | {ms([x['bleu'] for x in rs])} | "
            f"{ms([x['com'] for x in rs])} | {r}/{w} | {'< 0.001' if p < 0.001 else f'{p:.3f}'} | "
            f"{ms([x['shuf'] for x in rs], '{:+.2f}')} | {ms([x['soft'] for x in rs])} | {ms([x['auc'] for x in rs], '{:.3f}')} |")


HEAD = ("| System | Seeds | Val BLEU | Test2016 BLEU | CoMMuTE acc. % | Both right / both wrong (pooled) | Sign-test p | "
        "BLEU gain, correct vs shuffled image | Software BLEU | Gate AUC (metaphor vs other) |\n|" + "---|" * 10)


def table(title, systems, note=""):
    print(f"\n## {title}\n")
    if note:
        print(note + "\n")
    print(HEAD)
    for s in systems:
        print(row(*s) if isinstance(s, tuple) else row(s))


